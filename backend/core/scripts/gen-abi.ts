/**
 * `pnpm abi`: generate backend/core/src/abi.ts from Foundry artifacts in contracts/out (never hand-written, P4).
 * Builds first so the ABIs always match the current Solidity. The output is committed so teammates without Foundry
 * can still build the backend and frontend.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { contractsDir, coreDir, run } from "./run.ts";

const artifacts: Array<[exportName: string, file: string, contract: string]> = [
  ["avenHookAbi", "AvenHook.sol", "AvenHook"],
  ["poolManagerAbi", "PoolManager.sol", "PoolManager"],
  ["poolSwapTestAbi", "PoolSwapTest.sol", "PoolSwapTest"],
  ["poolModifyLiquidityTestAbi", "PoolModifyLiquidityTest.sol", "PoolModifyLiquidityTest"],
  ["mockErc20Abi", "MockERC20.sol", "MockERC20"],
  ["mockHyperCorePxAbi", "MockHyperCorePx.sol", "MockHyperCorePx"],
];

run("forge", ["build"], contractsDir);

let out = "// GENERATED by backend/core/scripts/gen-abi.ts from contracts/out. Do not edit; run `pnpm abi`.\n\n";
for (const [name, file, contract] of artifacts) {
  const art = JSON.parse(readFileSync(join(contractsDir, "out", file, `${contract}.json`), "utf8")) as { abi: unknown[] };
  out += `export const ${name} = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(coreDir, "src", "abi.ts"), out);
console.log(`wrote src/abi.ts (${artifacts.length} ABIs)`);
