/**
 * `pnpm --filter @aven/arena loadtest:report`: writes docs/LOADTEST.md from backend/data/load/{onchain,loadtest}.json
 * (PLAN 7.4). Regenerate after `LOAD=1 forge test --match-path test/load/OnchainLoad.t.sol` and `pnpm loadtest`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dataDir = fileURLToPath(new URL("../../data/load/", import.meta.url));
const docs = fileURLToPath(new URL("../../../docs/LOADTEST.md", import.meta.url));
const on = JSON.parse(readFileSync(`${dataDir}onchain.json`, "utf8"));
const lt = JSON.parse(readFileSync(`${dataDir}loadtest.json`, "utf8"));
const A = lt.onchainBurst;
const B = lt.apiLoad;
const C = lt.stress;
const k = (n: number) => n.toLocaleString("en-US");
const L: string[] = [];
const md = (s = "") => L.push(s);

md("# LOADTEST.md — load and stress results");
md();
md(`Generated by \`pnpm --filter @aven/arena loadtest:report\` from \`backend/data/load/*.json\` (harness run ${lt.startedAt} → ${lt.finishedAt}). Everything runs locally on a Windows laptop: anvil with the real deploy scripts, \`MockHyperCorePx\` at the precompile addresses, and the Arena service in-process. To reproduce:`);
md();
md("```bash");
md("cd contracts && LOAD=1 forge test --match-path test/load/OnchainLoad.t.sol -vv   # 7.1(a) -> backend/data/load/onchain.json");
md("pnpm --filter @aven/arena loadtest                                              # 7.1(b), 7.2, 7.3 -> backend/data/load/loadtest.json");
md("pnpm --filter @aven/arena loadtest:report                                       # -> this file");
md("```");
md();
md("## 7.1 On-chain load");
md();
md("### (a) Foundry stress: many Aven swaps per block, broken reads injected");
md();
md(`- **Run:** ${k(on.swaps)} swaps over ${on.blocks} blocks, up to ${on.maxSwapsPerBlock} per block. Both directions, a quarter of them exact-out. The oracle moves ±4% and the mark ±0.8% every block, and ~15% of blocks get a broken read (revert, gas burn, empty or >uint64 return).`);
md(`- **Correctness under load:**`);
md(`  - **${on.reverts} reverts** (I1);`);
md(`  - **${on.feeViolations} fee violations** (I2: in [min, max] or exactly fallback);`);
md(`  - **${on.zeroFeeSwaps} zero-fee swaps** (I3);`);
md(`  - **${on.topOfBlockViolations} top-of-block violations** (one top price per block);`);
md(`  - **${on.anchorViolations} anchor violations** (the anchor moves at most once per timestamp);`);
md(`  - ${on.fallbackSwaps} fallback-fee swaps, all ${on.swapsUnderBrokenReads} of them under broken reads.`);
md(`- **Gas per swap** (full swap through the test router: router + PoolManager + hook): p50 **${k(on.swapGasP50)}**, p95 **${k(on.swapGasP95)}**, max ${k(on.swapGasMax)}. The hook's own share is ~47k (PROOFS.md).`);
md(`- **Gas per block** of those swaps: p95 ${k(on.blockGasP95)}, max ${k(on.blockGasMax)}, against the ${k(on.smallBlockGasLimit)} HyperEVM small block.`);
md(`- **Finding: capacity, not a bug.** One small block fits **~16 Aven swaps** (vs ~24 plain swaps at ~123k). Extra swaps land in the next block 1 s later; fees stay correct because top-of-block is per block.`);
md();
md("### (b) Real burst on the local chain");
md();
md(`- **Run:** 7 wallets fired **${A.sent} swaps** at the Aven pool without waiting, all sent in ${k(A.sendMs)} ms.`);
md(`- **Results:**`);
md(`  - **${A.success} succeeded, ${A.reverted} reverted**;`);
md(`  - mined in ${A.blocks} anvil blocks (max ${A.maxSwapsPerBlock} swaps / ${k(A.maxBlockGasOfSwaps)} gas in one block; anvil blocks are 30M gas);`);
md(`  - ${A.blocksWithMoreThanOneTopPrice} blocks with more than one top-of-block price.`);
md(`- \`verify --all\` over the burst: **${A.verify.events} FeeComputed events, check A ${A.verify.checkA}/${A.verify.events}, check B ${A.verify.checkB}/${A.verify.events}, ${A.verify.mismatches} mismatches**.`);
md();
md("## 7.2 Arena API under load (bot running, oracle moving every 4 s, 200 SSE clients connected)");
md();
md("| Route | req/s | p50 ms | p97.5 ms | p99 ms | max ms | total | errors | timeouts | non-2xx |");
md("|---|---|---|---|---|---|---|---|---|---|");
for (const [route, r] of Object.entries(B.routes as Record<string, Record<string, number>>)) {
  md(`| \`${route}\` | ${k(r.reqPerSec!)} | ${r.p50} | ${r.p97_5} | ${r.p99} | ${r.max} | ${k(r.total!)} | ${r.errors} | ${r.timeouts} | ${r.non2xx} |`);
}
md();
md("50 concurrent connections, 15 s per route (autocannon).");
md();
md(`- **SSE:** ${B.sse.clients} concurrent \`/stream\` clients. ${B.sse.subscribersDuringLoad} subscribed during the load; every client received ≥ ${B.sse.minEventsPerClient} events; ${B.sse.clientErrors} client errors. **${B.sse.subscribersAfterClose} subscribers remained after the clients closed** (no leak).`);
md(`- **Bot kept up:** the chain made ${B.bot.chainBlocksDuringLoad} blocks during the load; the bot ran ${B.bot.botIterationsDuringLoad} iterations and made ${B.bot.arbTradesDuringLoad} arb trades. Its last run was at block ${B.bot.lastRunBlock} with head ${B.bot.headAfter}.`);
md(`- **POST rate limit:** ${B.rateLimit.sent} POSTs from one client → **${B.rateLimit.ok} accepted, ${B.rateLimit.limited} rejected with 429** (limit 30/min).`);
md(`- **Memory:** heap after GC ${B.memoryMB.heapBefore} → ${B.memoryMB.heapAfter} MB (flat, no leak). RSS ${B.memoryMB.rssBefore} → ${B.memoryMB.rssAfter} MB, which includes the in-process autocannon workers and 200 open sockets.`);
md();
md("## 7.3 Bot under stress (shocks while the RPC is flaky, then down, then healthy)");
md();
md("- **RPC fault proxy** in front of the Arena: \"flaky\" = 20% HTTP 503 + 10% responses held 20 s (beyond the 15 s client timeout); \"down\" = every request fails.");
md(`  - Totals: ${k(C.proxy.requests)} proxied requests, ${C.proxy.failed503} injected 503s, ${C.proxy.hung} injected timeouts.`);
md(`- **Shocks:** ${C.shocks.map((s: { phase: string; ok: boolean }) => `${s.phase} ${s.ok ? "✓" : "✗"}`).join(", ")}. Failed shocks are RPC failures reported to the caller, as intended.`);
md(`- **Service stayed up:** \`/health\` ${C.health.ok} OK / ${C.health.failed} failed, probed every 500 ms through all phases.`);
md(`- **Loop never crashed:** ${C.loop.iterations} bot iterations, ${C.loop.iterationErrors} iteration errors and ${C.loop.pollErrors} poll errors, all caught and recorded as \`lastError\`. ${C.arbTradesAfterRecovery} arb trades after the RPC recovered.`);
md(`- **Nonces stayed consistent:** ${C.nonceErrors} nonce errors seen. \`verify --all\` over everything since the start of the run gives **${C.verifyAllSinceStart.events} events, ${C.verifyAllSinceStart.checkA}/${C.verifyAllSinceStart.events} check A, ${C.verifyAllSinceStart.checkB}/${C.verifyAllSinceStart.events} check B**.`);
md(`- **Auto-pause:** with \`MIN_NATIVE_BALANCE\` above the bot's balance, one iteration left the bot **enabled = ${C.autoPause.enabledAfter}** with \`lastError\`: "${C.autoPause.lastError}".`);
md(`- **Errors observed (sample):** ${C.distinctErrorsSeen.map((e: string) => `\`${e.replace(/`/g, "'")}\``).join("; ")}.`);
md();
md("## Findings and fixes");
md();
md("1. **Fixed: stale block number (found by 7.1(b) and 7.2).** viem caches `getBlockNumber()` for ~4 s by default.");
md("   - **Impact:**");
md("     - (a) `verifyAll` / `pnpm verify --all` run right after a burst computed its scan end from a stale head and found **0 of 280** events;");
md("     - (b) the Arena poller (every 500 ms) saw only ~1 block in 4: **10 bot iterations over 74 blocks**.");
md("   - **Fix:** `cacheTime: 0` in `verifyAll`, the verify CLI client, the Arena client and the local-chain client.");
md("   - **Regression tests:**");
md("     - `verifyAll asks for the live head (cacheTime 0)` (`backend/core/test/chain.test.ts`);");
md("     - `public client never caches the block number` (`backend/arena/test/chain.test.ts`).");
md("     - Both fail when the fix is removed (mutation-checked).");
md("   - Every number above is from the final run, after all fixes.");
md("2. **Fixed: slow receipt polling (found by 7.2 after fix 1).** `waitForTransactionReceipt` polls at the client's `pollingInterval`, which viem defaults to 4 s.");
md("   - **Impact:** with 1 s blocks every bot trade waited up to 4 s for its receipt, so a two-pool iteration took 8 s+. Measured: **11 iterations over 75 blocks** under API load.");
md("   - **Fix:** `pollingInterval: 250` on the Arena clients.");
md("   - **Regression:** `backend/arena/test/chain.test.ts` asserts the 250 ms interval.");
md("3. **Fixed: /state thundering herd (found by 7.2).** The per-block cache was filled only after the computation finished, so on every new block all concurrent callers recomputed /state (~10 RPC reads each). Measured: **p99 1,188 ms**.");
md("   - **Fix:** one in-flight computation per block, shared by all callers; failures aren't cached.");
md("   - **Regression:** `backend/arena/test/state.test.ts` (50 concurrent calls → 1 computation; mutation-checked: without the fix it's 50).");
md("4. **Fixed: first swap of a block ran out of gas (found by 7.3).** Bot txs were mined and reverted.");
md("   - **Diagnosis:** `pnpm --filter @aven/arena repro:reverts` reproduced it with the bot alone (no shocks, no RPC faults): **12 of 70** bot txs reverted. Every one was the first tx of its block and succeeded when replayed at the parent block.");
md("   - **Cause:** `eth_estimateGas` runs against the latest block. If a swap already happened there, the hook's top-of-block and anchor are already written, so the estimate takes the cheap path. The real tx executes as the first swap of the next block, where the hook writes both, so it runs out of gas.");
md("   - **Fix:** `withGasMargin` (estimate × 1.3 + 30k) on every Arena swap.");
md("   - **After the fix:** **0 of 76** reverted, and 74 arb trades recorded vs 56.");
md("   - **Regression:** the `withGasMargin` unit test; `repro:reverts` exits non-zero on any revert.");
md("   - **This applies to every router or wallet integrating Aven:** estimate with a margin (docs/SECURITY.md).");
md("5. **Accepted: block capacity.** ~16 Aven swaps fit one 3M-gas small block (full swap ~175–188k gas, the hook ~47k of it). Extra swaps spill into the next block; correctness is unaffected.");
md("6. **Accepted: shocks fail while the RPC is down.** The Arena reports the error to the admin and doesn't retry a shock forever. The bot loop itself retries with backoff and resumes when the RPC returns.");
md("7. **Accepted: a simulation can fail when another swap moves the pool between planning and simulation** (e.g. a shock). The iteration records the error and the next block re-plans; nothing is sent for a failed simulation.");
writeFileSync(docs, `${L.join("\n")}\n`);
